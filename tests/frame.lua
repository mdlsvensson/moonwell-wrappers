    panel:destroy()
end)

test('a frame reached through getParent, or an origin frame, is never made a part', function()
    local ui = Frame.origin(ORIGIN_FRAME_GAME_UI)
    native('BlzFrameSetParent', function(raw, parent) raw.parent = parent end)
    -- Chain B1: a borrowed part moved under the game UI, then found through its owner, then asked for its parent.
    local panel = Frame.create('Panel', ui)
    local title = Frame.byName('PanelTitle', panel.handle.context)
    title:setParent(ui)
    eq(panel:findChild('PanelTitle'), title)
    eq(title:getParent(), ui)
    panel:destroy()
    eq(title:isDisposed(), true)
    eq(ui:isDisposed(), false)
    local holder = Frame.fromHandle(newFrame('HolderB1', nil, 0))
    ui:setParent(holder)
    local again = Frame.create('Panel', ui)
    again:destroy()
    -- A converted part whose parent is a known borrowed frame gets that same wrapper, and it stays borrowed.
    local second = Frame.create('Panel', ui)
    local middle = Frame.fromHandle(newFrame('MiddleBorrowed', nil, 0))
    local part = Frame.byName('PanelTitle', second.handle.context)
    part:setParent(middle)
    eq(second:findChild('PanelTitle'), part)
    eq(part:getParent(), middle)
    second:destroy()
    eq(part:isDisposed(), true); eq(middle:isDisposed(), false)
    middle:setParent(ui)
    failsAt(function() middle:destroy() end, 'Frame.destroy: only frames made by Frame.create')
    -- An origin frame that an owned frame's getChild or findChild returns stays borrowed.
    local third = Frame.create('Panel', ui)
    native('BlzFrameGetChild', function(raw, index)
        if raw == third.handle and index == 7 then return ORIGIN end
        return raw.children[index + 1]
    end)
    native('BlzGetFrameByName', function(name, context)
        if name == 'OriginAlias' then return ORIGIN end
        return byName[name .. '#' .. context]
    end)
    eq(third:getChild(7), ui); eq(third:findChild('OriginAlias'), ui)
    third:destroy()
    eq(ui:isDisposed(), false)
    local fourth = Frame.create('Panel', ui)
    fourth:destroy()
    native('BlzFrameGetChild', function(raw, index) return raw.children[index + 1] end)
    native('BlzGetFrameByName', function(name, context) return byName[name .. '#' .. context] end)
    native('BlzFrameSetParent', function() end)
end)
