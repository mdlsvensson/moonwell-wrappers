test('a template part first reached as borrowed becomes a part when it is found through its owner', function()
    local ui = Frame.origin(ORIGIN_FRAME_GAME_UI)
    -- Frame.byName first, then findChild: the same wrapper.
    local panel = Frame.create('Panel', ui)
    local title = Frame.byName('PanelTitle', panel.handle.context)
    eq(panel:findChild('PanelTitle'), title)
    -- It is a part from then on: it can be neither destroyed nor moved.
    resetCalls()
    failsAt(function() title:destroy() end, 'Frame.destroy: only frames made by Frame.create')
    failsAt(function() title:setParent(ui) end, 'Frame.setParent: a template part cannot be re-parented')
    eq(totalCalls(), 0)
    -- Its owner's destroy disposes it, and it is recorded once however often it is found.
    eq(panel:getChild(0), title); eq(panel:findChild('PanelTitle'), title)
    panel:destroy()
    eq(title:isDisposed(), true)
    failsAt(function() title:getName() end, 'Frame.getName: Frame is disposed')
    -- The control: findChild first, then Frame.byName.
    local second = Frame.create('Panel', ui)
    local found = second:findChild('PanelTitle')
    eq(Frame.byName('PanelTitle', second.handle.context), found)
    second:destroy()
    eq(found:isDisposed(), true)
    -- Frame.fromHandle first, then getChild.
    local third = Frame.create('Panel', ui)
    local close = Frame.fromHandle(third.handle.children[2])
    eq(third:getChild(1), close)
    third:destroy()
    eq(close:isDisposed(), true)
    -- A part's parent that was reached as borrowed first stays borrowed through getParent; getChild makes it a part.
    local fourth = Frame.create('Panel', ui)
    newFrame('PanelInner', fourth.handle.children[1], fourth.handle.context)
    local middle = Frame.fromHandle(fourth.handle.children[1])
    local inner = fourth:findChild('PanelInner')
    eq(inner:getParent(), middle)
    eq(fourth:getChild(0), middle)
    fourth:destroy()
    eq(middle:isDisposed(), true); eq(inner:isDisposed(), true)
    -- A frame of the game's that no owned frame leads to stays borrowed.
    local loose = Frame.fromHandle(newFrame('LooseTwo', nil, 0))
    loose:setParent(ui)
    failsAt(function() loose:destroy() end, 'Frame.destroy: only frames made by Frame.create')
end)

